//! Shared helpers for the canonical query-loop tool execution boundary.
//!
//! `QueryDeps::execute_tool` is the only full tool execution entry point. This
//! module intentionally exposes only reusable security/result helpers so tool
//! lookup, validation, hooks, permissions, audit, progress, execution, and
//! result preservation cannot drift across duplicate pipelines.

mod security;
#[cfg(test)]
mod tests;

use std::time::Instant;

use serde_json::Value;

use crate::types::tool::ToolResult;

#[cfg(test)]
pub(crate) use security::with_sandbox_availability_override;
pub(crate) use security::{
    find_tool, is_plan_mode_plan_file_write, sandbox_allowed_command_applies, security_validate,
};

/// Result of an early security-stage rejection before canonical execution
/// reaches the tool call.
#[derive(Debug)]
pub struct ToolExecutionResult {
    /// The tool_use_id that triggered this execution.
    pub tool_use_id: String,
    /// The resolved tool name.
    pub tool_name: String,
    /// The tool result data.
    pub result: ToolResult,
    /// Whether the result is an error.
    pub is_error: bool,
    /// New messages generated by the tool.
    pub new_messages: Vec<crate::types::message::Message>,
    /// Whether a post-tool hook stopped continuation.
    pub hook_stopped_continuation: bool,
}

/// Create an error result for early termination.
fn make_error_result(
    tool_use_id: &str,
    tool_name: &str,
    message: &str,
    _started: Instant,
) -> ToolExecutionResult {
    ToolExecutionResult {
        tool_use_id: tool_use_id.to_string(),
        tool_name: tool_name.to_string(),
        result: ToolResult {
            data: Value::String(message.to_string()),
            new_messages: vec![],
            ..Default::default()
        },
        is_error: true,
        new_messages: vec![],
        hook_stopped_continuation: false,
    }
}
